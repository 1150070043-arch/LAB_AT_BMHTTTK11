    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed


String ciphertext = jTextArea2.getText();

if (ciphertext.trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Hãy nhập Ciphertext trước khi giải mã.");
    return;
}

try {
    String key = jTextField1.getText().trim();

    PlayfairCipher cipher = new PlayfairCipher(key);

    jTextArea1.setText(cipher.decrypt(ciphertext));
    jTextArea3.setText(PlayfairCipher.getKeyMatrix(key));

    jLabel5.setText("Đã giải mã Playfair với khóa " + key + ".");

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this,
            ex.getMessage(),
            "Dữ liệu không hợp lệ",
            JOptionPane.ERROR_MESSAGE);
}

        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed



String plaintext = jTextArea1.getText();

if (plaintext.trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Hãy nhập Plaintext trước khi mã hóa.");
    return;
}

try {
    String key = jTextField1.getText().trim();

    PlayfairCipher cipher = new PlayfairCipher(key);

    jTextArea2.setText(cipher.encrypt(plaintext));
    jTextArea3.setText(PlayfairCipher.getKeyMatrix(key));

    jLabel5.setText("Đã mã hóa Playfair với khóa " + key + ".");

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this,
            ex.getMessage(),
            "Dữ liệu không hợp lệ",
            JOptionPane.ERROR_MESSAGE);
}


    }//GEN-LAST:event_jButton1ActionPerformed

